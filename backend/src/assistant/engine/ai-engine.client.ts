/**
 * The boundary between the Node API and the Python engine.
 *
 * NestJS owns identity, sessions and validation; the engine owns the
 * conversation. Everything crossing this seam is a plain value -- no
 * engine object, no stack trace and no file path -- so a failure inside
 * Python cannot become a leak out of the browser-facing API.
 */

export interface EngineWorkflow {
  name: string | null;
  state: string;
  step: number | null;
  totalSteps: number | null;
}

export interface EngineReply {
  reply: string;
  /** Present only when the turn began as speech. */
  transcript?: string | null;
  workflow?: EngineWorkflow | null;
  /** True when the customer asked to end the session. */
  ended?: boolean;
}

export interface EngineTextTurn {
  sessionId: string;
  language: string;
  text: string;
}

export interface EngineAudioTurn {
  sessionId: string;
  language: string;
  audio: Buffer;
  mimeType: string;
  filename: string;
}

export interface EngineSpeech {
  audio: Buffer;
  /** Derived from the generated bytes, not assumed. */
  contentType: string;
}

export interface EngineSpeechRequest {
  text: string;
  language: string;
}

export abstract class AiEngineClient {
  abstract sendText(turn: EngineTextTurn): Promise<EngineReply>;
  abstract sendAudio(turn: EngineAudioTurn): Promise<EngineReply>;
  /** Turns reply text into speech. Stateless: no conversation is touched. */
  abstract synthesize(request: EngineSpeechRequest): Promise<EngineSpeech>;
  /** Releases the engine-side conversation when a visit ends. */
  abstract endSession(sessionId: string): Promise<void>;
}

/**
 * Raised when the engine cannot answer.
 *
 * Carries a message already safe to show a customer; the service turns
 * it into the API's standard error shape.
 */
export class AiEngineError extends Error {
  readonly status: number;

  constructor(message: string, status = 502) {
    super(message);
    this.name = 'AiEngineError';
    this.status = status;
  }
}
