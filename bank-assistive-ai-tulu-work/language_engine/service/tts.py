"""
Speech synthesis for the web client.

The engine already knows how to turn a reply into speech: it has a
Markdown sanitiser so TTS does not read punctuation aloud, and a
language-to-voice map. Both are reused here rather than copied.

What is NOT reused is playback. `TextToSpeech.speak()` renders audio and
then plays it through pygame on the server, which is right for someone
sitting at that terminal and useless for a browser. This module stops at
the bytes and lets the browser do the playing. `speak()` is left exactly
as it is for the CLI.

Synthesis is stateless: text plus an authoritative language in, audio
out. It never touches ConversationManager, and nothing about it belongs
to a session.
"""

from __future__ import annotations

import asyncio
import logging
import os
import tempfile
from contextvars import ContextVar
from typing import Awaitable, Callable, Mapping, Optional, Tuple

# The one definition of the effective session language (M2), shared with the
# registry so the voice is chosen from exactly the language the turn used.
# Re-exported under its existing name: callers importing it from here keep
# working.
from service.language import normalise_language
from app.speech.speech_plan import (
    UnsupportedScriptError,
    UnsupportedSpeechLanguageError,
    plan_speech,
)

#: Long enough for any assistant reply, short enough that a malicious
#: caller cannot ask for hours of audio.
MAX_TTS_CHARS = 2000

#: Fallback when the generated bytes cannot be identified.
DEFAULT_CONTENT_TYPE = "audio/mpeg"

#: Tulu has no voice of its own: Kannada-script Tulu is read by the Kannada voice.
TULU = "tcy"
TULU_VOICE_LANGUAGE = "kn"

logger = logging.getLogger("assistant-service.tts")

#: Correlation id of the /tts request being served, set by the HTTP handler.
#: A context variable rather than a parameter so synthesize() keeps its
#: signature; "-" outside a request.
request_id: ContextVar[str] = ContextVar("tts_request_id", default="-")

# Failure categories. Stable identifiers, safe to return to the caller and to
# log: each names WHERE synthesis stopped, never what the text was.
EMPTY_TEXT = "empty_text"
TEXT_TOO_LONG = "text_too_long"
EMPTY_AFTER_CLEANING = "empty_after_cleaning"
UNSUPPORTED_LANGUAGE = "unsupported_language"
UNSUPPORTED_SCRIPT = "unsupported_script"
SYNTHESIS_FAILED = "synthesis_failed"
EMPTY_AUDIO = "empty_audio"


class TtsError(RuntimeError):
    """Raised when speech could not be produced. Message is customer-safe."""

    category = SYNTHESIS_FAILED

    def __init__(self, message: str, category: Optional[str] = None) -> None:
        super().__init__(message)
        if category is not None:
            self.category = category


class UnsupportedLanguageError(TtsError):
    """Raised when no voice exists for the requested language."""

    category = UNSUPPORTED_LANGUAGE


def _log(level: int, event: str, **fields) -> None:
    """
    One key=value line per event, always carrying the request id.

    Callers pass lengths, voices, categories and exception TYPES only. The
    reply text is never logged (it can hold amounts and account numbers),
    and neither are exception messages: edge-tts and aiohttp put request
    URLs, including the service's client token, into theirs.
    """
    parts = " ".join(f"{key}={value}" for key, value in fields.items())
    logger.log(level, "%s request_id=%s %s", event, request_id.get(), parts)


def _describe_exception(error: BaseException) -> dict:
    """The safe identifying parts of an exception: type, and status if any."""
    kind = type(error)
    described = {"exc_type": f"{kind.__module__}.{kind.__qualname__}"}

    # aiohttp's handshake and response errors carry the HTTP status the voice
    # service answered with -- the single most useful fact about a refusal.
    status = getattr(error, "status", None)
    if isinstance(status, int):
        described["exc_status"] = status

    if isinstance(error, OSError) and error.errno is not None:
        described["exc_errno"] = error.errno

    return described


def validate_text(text: Optional[str]) -> str:
    """Checks the text is something worth speaking."""
    cleaned = (text or "").strip()

    if not cleaned:
        raise TtsError("There is nothing to read out.", EMPTY_TEXT)

    if len(cleaned) > MAX_TTS_CHARS:
        raise TtsError("That response is too long to read out.", TEXT_TOO_LONG)

    return cleaned


def select_voice(language: Optional[str], voices: Mapping[str, str]) -> str:
    """
    Picks the Edge voice for a language.

    The map is the engine's own, so the web and the CLI speak in the same
    voices. An unknown language is refused rather than quietly answered
    in English -- a Kannada speaker hearing an English voice would have
    no idea why.
    """
    key = normalise_language(language)
    # Tulu is read by the Kannada voice (Kannada-script Tulu text); see
    # app/tulu/tts/synthesizer.py for why and what that does not claim.
    voice = voices.get(TULU_VOICE_LANGUAGE if key == TULU else key)

    if not voice:
        raise UnsupportedLanguageError(f"No voice is available for language '{key}'.")

    return voice


def detect_content_type(audio: bytes) -> str:
    """
    Identifies the generated audio from its leading bytes.

    Edge TTS returns MP3 today, but declaring a Content-Type from an
    assumption is how a browser ends up refusing to play a file that is
    perfectly valid. This looks instead of guessing.
    """
    return _identify_audio(audio) or DEFAULT_CONTENT_TYPE


def is_recognised_audio(audio: bytes) -> bool:
    """True when the bytes start with a signature detect_content_type knows."""
    return _identify_audio(audio) is not None


def _identify_audio(audio: bytes) -> Optional[str]:
    """The content type the leading bytes prove, or None."""
    if len(audio) >= 3 and audio[:3] == b"ID3":
        return "audio/mpeg"

    # MPEG frame sync: eleven set bits.
    if len(audio) >= 2 and audio[0] == 0xFF and (audio[1] & 0xE0) == 0xE0:
        return "audio/mpeg"

    if len(audio) >= 12 and audio[:4] == b"RIFF" and audio[8:12] == b"WAVE":
        return "audio/wav"

    if len(audio) >= 4 and audio[:4] == b"OggS":
        return "audio/ogg"

    return None


def load_engine_speech() -> Tuple[Callable[[str], str], Mapping[str, str]]:
    """
    Borrows the engine's sanitiser and voice map.

    Imported lazily on purpose. The engine's tts module imports edge_tts
    and pygame at module level, and this service should not require
    either to be importable until speech is actually asked for. Importing
    it does not touch audio hardware: the mixer is initialised on first
    playback, which the web path never reaches.
    """
    from app.speech.tts import TextToSpeech, sanitize_for_speech

    return sanitize_for_speech, TextToSpeech.VOICES


#: Writes speech for `text` in `voice` to `path`.
AudioGenerator = Callable[[str, str, str], Awaitable[None]]


async def _edge_tts_generator(text: str, voice: str, path: str) -> None:
    """The engine's own synthesis call, without its playback."""
    import edge_tts

    await edge_tts.Communicate(text, voice).save(path)


async def synthesize(
    text: str,
    language: str,
    *,
    generator: Optional[AudioGenerator] = None,
    voices: Optional[Mapping[str, str]] = None,
    sanitizer: Optional[Callable[[str], str]] = None,
) -> Tuple[bytes, str]:
    """
    Turns a reply into audio bytes.

    The generator, voice map and sanitiser are injectable so this can be
    exercised without Edge TTS installed; production passes none of them
    and gets the engine's own.

    VOICE SELECTION (M8). The session language must have a voice -- that
    check comes first, so an unsupported language is refused before
    anything is generated, as before. The voice for each part of the
    reply then follows the TEXT, not the session alone
    (app/speech/speech_plan): a Kannada sentence is read by the Kannada
    voice, an English sentence by the English voice, even in the same
    reply. An ordinary single-language reply is one synthesis call, as
    before; a mixed reply is one call per run of the same voice, and the
    MP3 parts are joined in order. Text in a script no voice can read is
    refused whole rather than read in part.

    Audio is written to uniquely named temporary files, read back, and
    deleted before returning. Nothing is kept, and the text is never
    logged.

    DIAGNOSTICS. Each request logs one tts.request line, then either
    tts.ok or one tts.failed line naming the category, the stage and --
    for a generator failure -- the original exception's type and any HTTP
    status, so a 422 can be traced to its cause from the server log alone.
    """
    language_key = normalise_language(language)
    _log(logging.INFO, "tts.request", language=language_key,
         chars_in=len(text or ""), empty_in=not (text or "").strip())

    try:
        cleaned = validate_text(text)
    except TtsError as error:
        _log(logging.WARNING, "tts.failed", category=error.category, stage="validate")
        raise

    if sanitizer is None or voices is None:
        engine_sanitizer, engine_voices = load_engine_speech()
        sanitizer = sanitizer or engine_sanitizer
        voices = voices if voices is not None else engine_voices

    speech_text = ""

    try:
        # The session language must be speakable at all.
        select_voice(language, voices)

        # Strips Markdown so the customer does not hear asterisks read aloud.
        speech_text = sanitizer(cleaned).strip()

        if language_key == TULU:
            # Romanized Tulu sentences become Kannada script for the Kannada
            # voice; English fallback sentences stay English for the English
            # voice. Replies rendered by the engine are already in Kannada
            # script and pass through unchanged.
            from app.tulu.tts.synthesizer import prepare_speech_text

            speech_text = prepare_speech_text(speech_text).spoken_text

        if not speech_text:
            raise TtsError("There is nothing to read out.", EMPTY_AFTER_CLEANING)

        segments = plan_segments(speech_text, language, voices)
    except TtsError as error:
        _log(logging.WARNING, "tts.failed", category=error.category, stage="plan",
             language=language_key, chars_clean=len(speech_text))
        raise

    _log(logging.INFO, "tts.plan", language=language_key, chars_clean=len(speech_text),
         segments=len(segments), voices=",".join(voice for _, voice in segments),
         provider="edge-tts" if generator is None else "injected")

    produce = generator or _edge_tts_generator
    parts = []

    for index, (segment_text, voice) in enumerate(segments, start=1):
        handle, path = tempfile.mkstemp(suffix=".mp3", prefix="reply-")
        os.close(handle)

        try:
            await produce(segment_text, voice, path)

            with open(path, "rb") as file:
                part = file.read()
        except TtsError as error:
            _log(logging.WARNING, "tts.failed", category=error.category, stage="generate",
                 segment=f"{index}/{len(segments)}", voice=voice)
            raise
        except Exception as error:
            # Network trouble reaching the voice service, an unusable voice
            # name, a disk problem -- none of which a customer can act on.
            # No partial audio is returned: half a reply can mislead.
            _log(logging.WARNING, "tts.failed", category=SYNTHESIS_FAILED, stage="generate",
                 segment=f"{index}/{len(segments)}", voice=voice, **_describe_exception(error))
            raise TtsError("The spoken reply could not be produced.", SYNTHESIS_FAILED) from error
        finally:
            try:
                os.remove(path)
            except OSError:
                # Best effort. The file is in the OS temp directory under a
                # random name and carries nothing identifying.
                pass

        if not part:
            _log(logging.WARNING, "tts.failed", category=EMPTY_AUDIO, stage="generate",
                 segment=f"{index}/{len(segments)}", voice=voice, bytes=0)
            raise TtsError("The spoken reply could not be produced.", EMPTY_AUDIO)

        parts.append(part)

    audio = join_mp3(parts)
    content_type = detect_content_type(audio)
    recognised = is_recognised_audio(audio)

    # Unrecognised bytes are still returned, as before: the browser is the
    # judge of what it can play. They are flagged, because a voice service
    # answering with something other than audio would otherwise look like
    # success here and an unplayable reply in the browser.
    _log(logging.INFO if recognised else logging.WARNING, "tts.ok", bytes=len(audio),
         content_type=content_type, recognised_audio=recognised, segments=len(parts))

    return audio, content_type


def plan_segments(text: str, language: str, voices: Mapping[str, str]):
    """[(text, voice)] for `text`: the speech plan, with voices resolved."""
    try:
        plan = plan_speech(text, language)
    except UnsupportedSpeechLanguageError as error:
        raise UnsupportedLanguageError(str(error)) from error
    except UnsupportedScriptError as error:
        raise UnsupportedLanguageError(
            "Part of this reply is in a language that cannot be read aloud.",
            UNSUPPORTED_SCRIPT,
        ) from error

    return [(segment.text, select_voice(segment.language, voices)) for segment in plan]


def _id3v2_length(data: bytes) -> int:
    """Length of a leading ID3v2 tag, or 0."""
    if len(data) < 10 or data[:3] != b"ID3":
        return 0
    size = 0
    for byte in data[6:10]:            # four 7-bit "synchsafe" bytes
        size = (size << 7) | (byte & 0x7F)
    footer = 10 if data[5] & 0x10 else 0
    return 10 + size + footer


def join_mp3(parts) -> bytes:
    """
    One playable MP3 from several, in order.

    MP3 is a sequence of self-contained frames, so parts in the same format
    can follow one another; only a leading ID3 tag would be read as
    mid-stream noise, so it is kept on the first part and dropped from the
    rest. Edge TTS produces every voice in the same format.
    """
    parts = list(parts)
    if not parts:
        return b""
    return parts[0] + b"".join(part[_id3v2_length(part):] for part in parts[1:])


def synthesize_sync(text: str, language: str, **kwargs) -> Tuple[bytes, str]:
    """Blocking wrapper, for callers that are not already async."""
    return asyncio.run(synthesize(text, language, **kwargs))
